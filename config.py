def get_soil_by_params(c, phi):
    """Подбор названия грунта по c и phi (для цветовой подсказки в GUI)."""
    best_name, best_dist = "Суглинок", float("inf")
    for name, s in SOIL_PRESETS.items():
        d = ((c - s["c"]) / max(s["c"], 1.0)) ** 2 + ((phi - s["phi"]) / 10.0) ** 2
        if d < best_dist:
            best_name, best_dist = name, d
    return best_name


